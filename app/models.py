# ==========================================
# ComicCraft - Pydantic Models
# ==========================================

from typing import List

from pydantic import BaseModel, Field


# ==========================================
# 1. Comic Generation Request
# ==========================================

class PromptRequest(BaseModel):
    """
    Data received from the JSON API
    when a user wants to generate a comic.
    """

    prompt: str = Field(
        ...,
        min_length=3,
        description="Main story idea"
    )

    character_name: str = Field(
        ...,
        min_length=1,
        description="Main character name"
    )

    setting: str = Field(
        ...,
        min_length=1,
        description="Story setting"
    )

    tone: str = Field(
        ...,
        min_length=1,
        description="Story tone"
    )

    art_style: str = Field(
        ...,
        min_length=1,
        description="Comic art style"
    )


# ==========================================
# 2. Comic Panel
# ==========================================

class ComicPanel(BaseModel):
    """
    Represents one comic panel
    generated by Gemini.
    """

    panel: int

    title: str

    scene_description: str

    image_prompt: str


# ==========================================
# 3. Comic Panel Result
# ==========================================

class ComicPanelResult(BaseModel):
    """
    Represents a generated comic panel
    after image generation.
    """

    panel: int

    title: str

    scene_description: str

    image_prompt: str

    image_path: str = ""

    text: str = ""


# ==========================================
# 4. Comic Generation Response
# ==========================================

class ComicResponse(BaseModel):
    """
    Response returned by the JSON comic API.
    """

    success: bool

    message: str

    layout: List[ComicPanelResult]

    pdf_path: str = ""


# ==========================================
# 5. Image Test Response
# ==========================================

class ImageTestResponse(BaseModel):
    """
    Response returned by the image
    testing endpoint.
    """

    success: bool

    image_path: str


# ==========================================
# 6. Health Check Response
# ==========================================

class HealthResponse(BaseModel):
    """
    Server health response.
    """

    status: str

    message: str